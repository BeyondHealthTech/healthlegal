export const PHYSICAL_ITEMS = CLINIC_ITEMS.filter((i) => i.physical)

export type ClinicAnswers = Record<string, string>

export function optionsFor(item: ClinicItem): string[] {
  return item.naAllowed
    ? [ANSWER_YES, ANSWER_NO, ANSWER_UNKNOWN, ANSWER_NA]
    : [ANSWER_YES, ANSWER_NO, ANSWER_UNKNOWN]
}

/** 回答を1文字/設問のコードにする（SDS診断と同じ方式）。未回答は x */
export function encodeClinicAnswers(answers: ClinicAnswers): string {
  return CLINIC_ITEMS.map((item) => {
    const i = optionsFor(item).indexOf(answers[item.id] ?? '')
    return i >= 0 ? String(i) : 'x'
  }).join('')
}

export function decodeClinicAnswers(code: string): ClinicAnswers | null {
  if (code.length !== CLINIC_ITEMS.length) return null
  const out: ClinicAnswers = {}
  for (let k = 0; k < CLINIC_ITEMS.length; k++) {
    const ch = code[k]
    if (ch === 'x') continue
    const i = Number(ch)
    const opts = optionsFor(CLINIC_ITEMS[k])
    if (!Number.isInteger(i) || i < 0 || i >= opts.length) return null
    out[CLINIC_ITEMS[k].id] = opts[i]
  }
  return out
}

export type ClinicResult = {
  yes: number
  no: number
  unknown: number
  na: number
  /** 「はい」でも「該当なし」でもない項目 */
  gaps: ClinicItem[]
  /** 現物確認4点のうち「はい」になっていないもの */
  physicalGaps: ClinicItem[]
}

export function evaluateClinic(answers: ClinicAnswers): ClinicResult {
  let yes = 0
  let no = 0
  let unknown = 0
  let na = 0
  const gaps: ClinicItem[] = []
  for (const item of CLINIC_ITEMS) {
    const a = answers[item.id]
    if (a === ANSWER_YES) yes++
    else if (a === ANSWER_NA) na++
    else {
      if (a === ANSWER_NO) no++
      else unknown++
      gaps.push(item)
    }
  }
  return { yes, no, unknown, na, gaps, physicalGaps: gaps.filter((g) => g.physical) }
}
